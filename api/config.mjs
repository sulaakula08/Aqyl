/**
 * Публичная конфигурация клиента.
 *
 * Проект собирается без сборщика, поэтому подставить переменные окружения
 * в бандл на этапе билда невозможно — бандла нет. Вместо того чтобы просить
 * человека руками править js-файл (и однажды закоммитить его вместе с чужим
 * ключом), отдаём конфигурацию отдельным эндпоинтом.
 *
 * Здесь только те значения, которые и так публичны: адрес проекта Supabase
 * и anon-ключ. Anon-ключ безопасен по устройству Supabase — он позволяет
 * ровно то, что разрешает Row Level Security, и попадает в браузер в любой
 * схеме использования. Service-role ключа здесь нет и быть не должно.
 */

export default async function handler(req, res) {
  if (req.method !== 'GET') {
    res.setHeader('Allow', 'GET');
    return res.status(405).json({ error: 'Метод не поддерживается' });
  }

  const url = process.env.SUPABASE_URL || '';
  const anonKey = process.env.SUPABASE_ANON_KEY || '';

  /* Не кэшируем вовсе.
     Сначала здесь стояло `s-maxage=300` — рассуждение было, что конфигурация
     меняется раз в жизни проекта. На практике это означало ровно одно: после
     подключения Supabase кнопка входа не появлялась ещё пять минут, потому
     что CDN продолжал отдавать старый ответ `auth: false`, и выглядело это
     как неработающий вход. Ответ весит двести байт, экономить на нём нечего,
     а расхождение между настройками и тем, что видит браузер, стоит дорого. */
  res.setHeader('Cache-Control', 'no-store');

  return res.status(200).json({
    supabase: url && anonKey ? { url, anonKey } : null,
    // Признак, по которому клиент решает, показывать ли вход вообще.
    features: { auth: Boolean(url && anonKey), tutor: Boolean(process.env.GEMINI_API_KEY) },
  });
}
