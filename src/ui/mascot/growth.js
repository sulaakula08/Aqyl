/**
 * Бүркіт растёт вместе с учеником.
 *
 * Идея, ради которой это вообще написано: прогресс в учёбе обычно показывают
 * числом, полоской или значком — то есть тем, что ученик пролистывает. Здесь
 * прогресс показывает сам персонаж. Пушистый птенец с огромной головой и
 * культяпками вместо крыльев превращается в степного беркута: голова
 * становится меньше относительно тела, крылья — длиннее, хохолок — острее,
 * хвост — шире. Ребёнок не читает эту шкалу, он её узнаёт.
 *
 * Четыре ступени привязаны к средней освоенности тем по выбранным предметам —
 * то есть к тому же числу, которое кабинет показывает кольцом. Никакой второй
 * «геймерской» валюты не заводим: если бы персонаж рос за время в приложении,
 * он бы врал, и первый же въедливый ученик это заметил.
 *
 * ─── Почему рост живёт в CSS-свойствах scale/translate, а не в transform ───
 *
 * Реакции (`machine.js`) пишут в `transform` целиком: строка перезаписывается
 * на каждой анимации. Если бы рост тоже жил там, любое движение крыла стирало
 * бы размах крыльев обратно к птенцу. Отдельные свойства `scale` и `translate`
 * применяются браузером ДО `transform` и с ним не спорят — размер держится
 * сам по себе, а поверх него свободно играют повороты и прыжки.
 */

const STAGE_COUNT = 4;

/**
 * Ступень 0…3 по средней освоенности.
 *
 * Пороги специально низкие внизу и разреженные вверху: первое превращение
 * должно случиться на первом же занятии (иначе его никто не увидит), а
 * последнее — быть редким и заслуженным.
 */
export function stageOf(avgMastery) {
  const m = Number.isFinite(avgMastery) ? avgMastery : 0;
  if (m >= 0.75) return 3;
  if (m >= 0.5) return 2;
  if (m >= 0.25) return 1;
  return 0;
}

/**
 * Пропорции по ступеням.
 *
 * Это не «стало больше», а смена сложения. Птенец: голова 1.12 от нормы,
 * крылья короче нормы, хохолок пух. Беркут: голова 0.94, крылья в полтора
 * раза длиннее и шире, хвост веером. Меняется силуэт — именно его глаз
 * узнаёт с одного взгляда, даже на экране в 74 пикселя.
 */
const SHAPE = [
  { head: 1.12, body: 0.96, wing: [0.88, 0.86], crest: [0.9, 0.8], tail: 0.82, beak: 0.92, brow: 0.9 },
  { head: 1.06, body: 1.00, wing: [0.98, 1.04], crest: [1.0, 1.05], tail: 0.96, beak: 1.00, brow: 1.0 },
  { head: 1.00, body: 1.04, wing: [1.08, 1.26], crest: [1.12, 1.3], tail: 1.14, beak: 1.08, brow: 1.1 },
  { head: 0.94, body: 1.08, wing: [1.18, 1.5], crest: [1.24, 1.55], tail: 1.32, beak: 1.16, brow: 1.2 },
];

/** Названия ступеней — для реплики в момент превращения. */
export const STAGE_KEYS = ['mascot.stage0', 'mascot.stage1', 'mascot.stage2', 'mascot.stage3'];

export function applyGrowth(parts, stage) {
  const s = SHAPE[Math.max(0, Math.min(STAGE_COUNT - 1, stage))];
  if (!s) return;

  const set = (part, scale, translate) => {
    const el = parts[part];
    if (!el) return;
    el.style.scale = scale;
    if (translate) el.style.translate = translate;
  };

  // Голова уменьшается относительно тела — и одновременно опускается, иначе
  // при уменьшении она бы «оторвалась» от шеи и повисла в воздухе.
  set('head', String(s.head), `0 ${((s.head - 1) * 22).toFixed(1)}px`);
  set('body', String(s.body));
  set('wingL', `${s.wing[0]} ${s.wing[1]}`);
  set('wingR', `${s.wing[0]} ${s.wing[1]}`);
  set('crest', `${s.crest[0]} ${s.crest[1]}`);
  set('tail', String(s.tail));
  set('beakBottom', String(s.beak));
  set('browL', `${s.brow} 1`);
  set('browR', `${s.brow} 1`);
}
