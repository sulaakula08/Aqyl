/**
 * Перемешивание вариантов ответа.
 *
 * В исходнике верный вариант всегда записан первым — так удобнее сопровождать
 * банк заданий. Но показывать его первым нельзя: ученик быстро выучит позицию,
 * а не материал. Перестановка детерминирована (выводится из id задания),
 * поэтому порядок стабилен между сессиями и воспроизводим при отладке.
 */
(function shuffleOptions() {
  const hash = (s) => {
    let h = 2166136261;
    for (let i = 0; i < s.length; i++) {
      h ^= s.charCodeAt(i);
      h = Math.imul(h, 16777619);
    }
    return h >>> 0;
  };

  ITEMS.forEach((item) => {
    let seed = hash(item.id);
    const rnd = () => {
      seed = (seed + 0x6D2B79F5) | 0;
      let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
      t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };

    const original = item.options;
    const order = original.map((_, i) => i);
    for (let i = order.length - 1; i > 0; i--) {
      const j = Math.floor(rnd() * (i + 1));
      [order[i], order[j]] = [order[j], order[i]];
    }
    item.options = order.map((i) => original[i]);
    item.answer = order.indexOf(item.answer);
  });
})();

